// Generates images.gen.ts files listing the images found in each asset folder.
// Wired into predev/prebuild — run manually with: bun run gen
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const targets = [
	{
		dir: "src/assets/recommendations",
		out: "src/content/recommendations/images.gen.ts",
	},
	{
		dir: "src/assets/projects",
		out: "src/content/projects/images.gen.ts",
	},
];

const IMAGE_EXT = /\.(webp|avif|png|jpe?g|svg)$/i;

for (const { dir, out } of targets) {
	const files = readdirSync(join(root, dir))
		.filter((name) => IMAGE_EXT.test(name))
		.sort();

	const body = `// AUTOGENERATED by scripts/generate-image-lists.mjs — do not edit.
// Regenerate with: bun run gen
export const imageFiles = [
${files.map((name) => `\t"${name}",`).join("\n")}
] as const;

export type ImageFile = (typeof imageFiles)[number];
`;

	writeFileSync(join(root, out), body);
	console.log(`generated ${out} (${files.length} files)`);
}
